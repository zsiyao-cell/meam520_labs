def IK_velocity_null(q_in, v_in, omega_in, b):
    """
    :param q_in: 1 x 7 vector corresponding to the robot's current configuration.
    :param v_in: The desired linear velocity in the world frame. If any element is
    Nan, then that velocity can be anything
    :param omega_in: The desired angular velocity in the world frame. If any
    element is Nan, then that velocity is unconstrained i.e. it can be anything
    :param b: 7 x 1 Secondary task joint velocity vector
    :return:
    dq - 1 x 7 vector corresponding to the joint velocities. If v_in and omega_in
         are infeasible, then dq should minimize the least squares error. If v_in
         and omega_in have multiple solutions, then you should select the solution
         that minimizes the l2 norm of dq
    """

    ## STUDENT CODE GOES HERE
    dq = np.zeros((1, 7))
    null = np.zeros((1, 7))
    b = b.reshape((7, 1))
    v_in = np.array(v_in)
    v_in = v_in.reshape((3,1))
    omega_in = np.array(omega_in)
    omega_in = omega_in.reshape((3,1))

    dq = IK_velocity(q_in, v_in, omega_in)
    J = calcJacobian(q_in)

    desired_velocity = np.concatenate((v_in.flatten(), omega_in.flatten()))

    mask = ~np.isnan(desired_velocity)
    J_reduced = J[mask, :]

    J_pinv = np.linalg.pinv(J_reduced)

    N = np.eye(7) - J_pinv @ J_reduced

    null = (N @ b).reshape((1, 7))

    return dq + null




